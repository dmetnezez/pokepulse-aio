export type StockStatus = 'in_stock' | 'out_of_stock' | 'limited' | 'preorder' | 'unknown';
export type TaskStatus = 'monitoring' | 'restock_detected' | 'out_of_stock' | 'paused' | 'error';
/**
 * `simulated` = generated by the demo engine. `live` = returned by an authorized retailer integration.
 * `email` = triggered by a retailer's own notification email arriving in the user's inbox.
 */
export type DataSource = 'simulated' | 'live' | 'email';
export type EventType = 'check' | 'restock' | 'sold_out' | 'price_change';
export type Channel = 'discord' | 'browser' | 'email' | 'telegram';
export type LogLevel = 'debug' | 'info' | 'warn' | 'error';
export type PurchaseAction = 'opened_page' | 'prepared' | 'checkout_ready' | 'purchased' | 'cancelled';

export const isAvailable = (s: StockStatus) => s === 'in_stock' || s === 'limited';

export interface Retailer {
  id: RetailerId;
  name: string;
  domain: string;
  country: string;
  integration_type: 'official_api' | 'affiliate_api' | 'partner_feed' | 'none';
  integration_status: 'available' | 'requires_credentials' | 'not_available';
  integration_notes: string;
  min_interval_sec: number;
  max_concurrency: number;
  request_spacing_ms: number;
  brand_color: string;
}

export interface Product {
  id: string;
  name: string;
  category: Category;
  set_name: string;
  language: 'EN' | 'JP';
  retailer_id: RetailerId;
  url: string;
  external_id: string | null;
  image_url: string | null;
  msrp: number | null;
  current_price: number | null;
  previous_price: number | null;
  stock_status: StockStatus;
  data_source: DataSource;
  last_restock_at: string | null;
  last_checked_at: string | null;
  created_at: string;
}

export interface UserRecord {
  id: string;
  email: string;
  display_name: string;
  password_hash?: string; // local mode only
  created_at: string;
}

export interface UserSettings {
  user_id: string;
  alert_email: string | null;
  discord_webhook_url: string | null;
  telegram_bot_token: string | null;
  telegram_chat_id: string | null;
  browser_notifications: boolean;
  default_frequency_sec: number;
  quiet_hours_start: number | null;
  quiet_hours_end: number | null;
  /** Inbox watcher: turns retailer "it's here" emails into instant alerts. */
  email_watch_enabled: boolean;
  imap_host: string;
  imap_port: number;
  imap_user: string | null;
  imap_password: string | null;
  /** comma-separated substrings matched against the From address */
  email_watch_senders: string;
  /** comma-separated; if set, the subject or body must contain one of them */
  email_watch_keywords: string;
  email_watch_last_uid: number | null;
  email_watch_status: string | null;
  email_watch_checked_at: string | null;
  /** open the drop page in the default browser on this computer when a drop email arrives */
  auto_open_links: boolean;
  /** hide everything the simulator produced and stop simulating this user's tasks */
  real_only: boolean;
}

export interface MonitoringTask {
  id: string;
  user_id: string;
  product_id: string;
  product_name: string;
  product_url: string;
  retailer_id: RetailerId;
  max_price: number | null;
  quantity: number;
  frequency_sec: number;
  /** tasks poll either the simulator or an authorized API; `email` events come from the inbox watcher */
  data_source: Exclude<DataSource, 'email'>;
  notify_discord: boolean;
  notify_browser: boolean;
  notify_email: boolean;
  notify_telegram: boolean;
  is_active: boolean;
  status: TaskStatus;
  last_checked_at: string | null;
  next_check_at: string;
  last_price: number | null;
  last_in_stock: boolean | null;
  check_count: number;
  restock_count: number;
  consecutive_errors: number;
  error_message: string | null;
  created_at: string;
  updated_at: string;
}

export interface StockHistoryRow {
  id: number;
  product_id: string;
  retailer_id: RetailerId;
  price: number | null;
  stock_status: StockStatus;
  in_stock: boolean;
  event_type: EventType;
  data_source: DataSource;
  latency_ms: number | null;
  checked_at: string;
}

export interface NotificationRow {
  id: string;
  user_id: string;
  task_id: string | null;
  product_id: string | null;
  channel: Channel;
  status: 'sent' | 'failed' | 'skipped' | 'queued';
  title: string;
  body: string;
  payload: Record<string, unknown>;
  error: string | null;
  created_at: string;
}

export interface PurchaseActivity {
  id: string;
  user_id: string;
  task_id: string | null;
  product_id: string | null;
  action: PurchaseAction;
  quantity: number;
  unit_price: number | null;
  note: string | null;
  created_at: string;
}

export interface TaskLog {
  id: number;
  user_id: string | null;
  task_id: string | null;
  level: LogLevel;
  message: string;
  context: Record<string, unknown>;
  created_at: string;
}

/** Events pushed to connected browsers over SSE. */
export type LiveEvent =
  | { type: 'activity'; event: ActivityItem }
  | { type: 'task'; task: MonitoringTask }
  | { type: 'notification'; notification: NotificationRow }
  | { type: 'log'; log: TaskLog }
  | { type: 'heartbeat'; at: string };

export interface ActivityItem {
  id: number;
  product_id: string;
  product_name: string;
  retailer_id: RetailerId;
  price: number | null;
  stock_status: StockStatus;
  event_type: EventType;
  data_source: DataSource;
  latency_ms: number | null;
  url: string;
  checked_at: string;
}
